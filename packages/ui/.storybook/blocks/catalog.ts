/** Storybook's id of a docs page, as `?path=/docs/<id>` links need it. */
export const docsId = (title: string) =>
  `${title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}--docs`;

